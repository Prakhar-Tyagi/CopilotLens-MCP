	private CreateParameterizedObjectAction createCreateParameterizedAction(IPinList pinlist, List<IAbstractPin> pins,
			boolean autogenerate, boolean reference, boolean placeAsStack, boolean placeAsGroup,
			List<IPinProxy> pinProxies, boolean withConductor)
	{
		if (pinlist instanceof IGenericInlineConnector) {
			return createPlaceInlineConnectorAction(getController(), (IGenericInlineConnector) pinlist, pins,
					autogenerate, reference, placeAsGroup, placeAsStack, pinProxies);
		}
		if (IConnector.Statics.isRingTerminalTypeConnector(pinlist)) {
			return createAddParameterizedRingTerminalAction(getController(), pinlist, pins, autogenerate, reference,
					pinProxies);
		}

		// this same action is used for all the other pinlists - should it be?
		return createAddParameterizedPinListAction(getController(), pinlist, pins, autogenerate, reference,
				placeAsStack, placeAsGroup, pinProxies, withConductor);
	}

	protected boolean onTerminate(boolean successful)
	{
		// terminate the appropriate sub-action
		boolean result = false;
		if (subAction instanceof AddInstanceAction) {
			// add as symbol
			result = ((AddInstanceAction) subAction).onTerminate(successful);
		}
		else if (subAction instanceof CreateByPointAction) {
			// add as parameterized instance
			result = ((CreateByPointAction) subAction).onTerminate(successful);
		}
		else if (subAction instanceof AddParameterizedSpliceAction) {
			// adds a parameterized splice instance - different sort of action / events
			//noinspection OverlyStrongTypeCast
			result = ((AddParameterizedSpliceAction) subAction).onTerminate(successful);
		}
		else if (subAction != null) {
			assert false : "Unknown sub-action " + subAction;
		}
		if (m_symbolledPLDialog != null) {
			// dts0100695613- the dialog contains a layer to draw the symbol on, to clean this layer, we should suspend
			// the undoable container so that internal objects wouldn't be added to the undo edit. Anyway, we are not
			// interested in any objects inside the dialog anymore.
			CAFUtils.getInstance().setTempUndoableContainer(UndoableContainerIdler.instance());
			m_symbolledPLDialog.cleanUp();
			// restore the original undoable edit.
			CAFUtils.getInstance().clearTempUndoableContainer();
		}
		cleanUp(successful);
		subAction = null;
		return result;
	}

