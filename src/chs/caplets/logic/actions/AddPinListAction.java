	protected boolean pinSelectionDialogRequired(IPinList pinlist)
	{

		// Pin selection for everything except splice and ICX (?)
		if ((pinlist instanceof ISplice || pinlist instanceof IInterconnectObject)) {
			return false;
		}
		// don't show dialog if no pins at all and no symbol
		return pinlist.getNumPins() > 0 || hasLibraryCavities(pinlist) || isBlockAndPinSelectionRequired(pinlist) ||
				(pinlist instanceof IMultiSymbolledPinlist && ((IMultiSymbolledPinlist) pinlist).getNumSymbols() > 0);
	}

	protected boolean hasLibraryCavities(IPinList pinlist)
	{
		ILibraryBaseObject libObj = pinlist.getLibraryObject();
		return libObj instanceof ILibraryCavityContainer && ((ILibraryCavityContainer) libObj).getNumCavities() > 0;
	}

	private boolean isBlockAndPinSelectionRequired(IPinList pinlist)
	{
		if (pinlist instanceof ILogicBlockDevice) {
			IBlockDevice block = (IBlockDevice) pinlist;
			List<IObjectDescriptor> unconnectedPins =
					BlockDeviceUnconnectedPinSelectionHelper.getUnconnectedPins(block);
			return !unconnectedPins.isEmpty() || block.getNumPins() > 0;
		}
		return false;
	}

	protected IActionEnum activateAddWithSymbol(ActionEvent e, IPinList pinlist, ISymbolDef symDef, IBlock block,
			Map<IUID, ISymbolledPin> map, boolean reference, boolean withConductor)
	{
		AddSymbolledPinListAction action =
				createAddSymbolledPinListAction(getController(), pinlist, symDef, block, map, reference, withConductor);
		subAction = action; // must set subAction before activating it so events are forwarded
		return action.onActivate(e);
	}

	protected IActionEnum activateAddWithoutSymbol(ActionEvent e, IPinList pinlist, List<IAbstractPin> pins,
			boolean autogenerate, boolean reference, boolean placeAsStack, boolean placeAsGroup,
			List<IPinProxy> pinProxies, boolean withConductor)
	{
		assert pinlist != null;
		assert pins != null;

		// nothing wrong with explicit initialization
		//noinspection UnusedAssignment
		IActionEnum result = IActionEnum.eCanceled;
		if (pinlist instanceof ISplice) {
			AddParameterizedSpliceAction action = createAddSpliceAction(getController(), (ISplice) pinlist);
			subAction = action; // must set subAction before activating it so events are forwarded
			result = action.onActivate(e);
		}
		else {
			CreateParameterizedObjectAction action =
					createCreateParameterizedAction(pinlist, pins, autogenerate, reference, placeAsStack, placeAsGroup,
							pinProxies, withConductor);
			subAction = action; // must set subAction before activating it so events are forwarded
			result = action.onActivate(e);
		}
		return result;
	}

