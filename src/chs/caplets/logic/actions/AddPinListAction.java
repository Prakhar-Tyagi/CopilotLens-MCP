	private boolean loadSharedUsagesIfNeeded(IPinList pinlist, Frame frame, String title)
	{
		ILogicDesign logicDesign = pinlist.getLogicDesign();
		if (logicDesign != null && pinlist.getSharedPinList() != null) {
			String longDes = ResourceMgr
					.getString(AddPinListAction.class, "AddPinListAction.LoadUsage.progress.longDescription");
			boolean loadedDesignMgrs = DesignSharedUsageHelper.loadeUsagesWithProgressBar(logicDesign.getProject(),
					frame, SharedPinHelper.getLogicDesignsUsingSharedPinList(logicDesign, pinlist.getSharedPinList()),
					title, title + " - " + pinlist.getName(), longDes);

			return !loadedDesignMgrs;
		}
		return true;
	}

	@Nullable private SymbolProxy getProxyWithBlock(SymbolProxy[] instances)
	{
		for (SymbolProxy symbolProxy : instances) {
			if (symbolProxy.isBlock()) {
				return symbolProxy;
			}
		}
		return null;
	}

	@Nullable private SymbolProxy getProxyWithSymbolDef(SymbolProxy[] instances)
	{
		for (SymbolProxy symbolProxy : instances) {
			if (!symbolProxy.isBlock()) {
				return symbolProxy;
			}
		}
		return null;
	}

