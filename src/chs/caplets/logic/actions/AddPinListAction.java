	protected IActionEnum onActivate(ActionEvent e)
	{
		// invoke the "Place ..." dialog for this pinlist type
		subAction = null;
		IPinList pinlist = getOperand();
		if (pinlist == null) {
			// dts0100591493: preventive fix (not reproduced), however previous assert is useless
			// without this test:
			assert false : "dts0100591493: Please try and record the steps";
			return IActionEnum.eCanceled;
		}

		if (!LogicObjectLockFinder.tryEdit(pinlist)) {
			return IActionEnum.eCanceled;
		}
		//melmorsy - FEAT12331
		//If the pinlist is an automatically generated plug connector, then don't allow instantiation!
		if (pinlist instanceof IHarnessPlugConnector && ((IHarnessPlugConnector) pinlist).getGenerationType() ==
				HarnessConnectorGenerationEnum.TypeAutomaticallyGenerated &&
				((IDeviceOwned) pinlist).getOwner() != null) {
			showInformationMessage(CAFUtils.getInstance().getDialogFrame(),
					ResourceMgr.getString(AddPinListAction.class, "AddPinListAction.AutoGeneratedPlug.Header"),
					ResourceMgr.getString(AddPinListAction.class, "AddPinListAction.AutoGeneratedPlug.Message",
							pinlist.getName()));
			return IActionEnum.eCanceled;
		}
		// don't show the dialog for splice without symbol
		List<IAbstractPin> pins = new ArrayList<IAbstractPin>();
		//pinProxies store the proxies for the pins which dont have a cable part yet - coming from library definition
		List<IPinProxy> pinProxies = new ArrayList<IPinProxy>();
		boolean autogenerate = true;
		boolean reference = false;
		boolean placeAsStack = false;
		boolean placeAsGroup = false;
		boolean withConductor = false;
		ISymbolDef symDef = loadSymbolDef(pinlist);
		IBlock block = null;
		Map<IUID, ISymbolledPin> symbolpinMap = null;
		if (pinSelectionDialogRequired(pinlist)) {
			// get all the options from the dialog
			Frame frame = CAFUtils.getInstance().getDialogFrame();
			String title = AddPinListDialog.getTitle(pinlist);
			if (!loadSharedUsagesIfNeeded(pinlist, frame, title)) {
				return IActionEnum.eCanceled;
			}
			if (!(pinlist instanceof IFunction) && pinlist instanceof IMultiSymbolledPinlist) {
				m_symbolledPLDialog = getAddMultiSymbolledPinListDialog(frame, title);
				enableSymbolView(m_symbolledPLDialog);
				ISharedPinReservationView pinview =
						FactoryMgr.getCommonFactory().constructSharedPinReservationView(pinlist.getSharedPinList());
				if (!m_symbolledPLDialog.selectPinList((IMultiSymbolledPinlist) pinlist, pinview,
						createPlacementOptionParams(pinlist, null))) {
					return IActionEnum.eCanceled;
				}
				for (Object pin : getSelectedPins()) {
					if (pin instanceof IAbstractPin) {
						pins.add((IAbstractPin) pin);
					}
					else if (pin instanceof IPinProxy) {
						IAbstractPin pinObj = ((IPinProxy) pin).getCablePin();
						if (pinObj != null) {
							pins.add(pinObj);
						}
						else {
							pinProxies.add((IPinProxy) pin);
						}
					}
				}

				autogenerate = m_symbolledPLDialog.getAutoGenerate();
				reference = m_symbolledPLDialog.getReference();
				placeAsStack = m_symbolledPLDialog.getPlaceAsStack();
				placeAsGroup = m_symbolledPLDialog.getPlaceAsGroup();
				IBooleanProperty withConductorOption = m_symbolledPLDialog.getWithConductorOption();
				withConductor = withConductorOption != null && withConductorOption.getValue();
				SymbolProxy[] symbolInstances = m_symbolledPLDialog.getSelectedSymbolInstances();
				if (m_symbolledPLDialog.isSymbelSelectionSelected() && symbolInstances.length > 0) {
					SymbolProxy proxy = getProxyWithSymbolDef(symbolInstances);
					if (proxy == null || proxy.getSymbolDef() == null) {
						proxy = getProxyWithBlock(symbolInstances);
						if (proxy != null) {
							block = proxy.getBlock();
							symDef = proxy.getSymbolDef();
						}
					}
					else {
						symDef = proxy.getSymbolDef();
					}
					if (proxy != null) {
						symbolpinMap = proxy.getPinsMapping();
					}
				}
				else {
					symDef = null;
					block = null;
				}
			}
			else {
				List<IPinProxy> pinSelection = new ArrayList<IPinProxy>();
				if (pinlist instanceof IBlockDevice /*&& Environment.isDesignHierarchyEnabled()*/) {
					final IBlockDevice blockDevice = (IBlockDevice) pinlist;
					PlaceBlockPinDialog placeBlockDialog =
							new PlaceBlockPinDialog(frame, new AddBlockPinActionModel(blockDevice), true,
									createPlacementOptionParams(blockDevice, null));
					IAddPinView.Result addPinView = placeBlockDialog.showDialog();
					if (addPinView == IAddPinView.Result.CANCEL) {
						return IActionEnum.eCanceled;
					}
					pinSelection.addAll(placeBlockDialog.getPins());
					autogenerate = placeBlockDialog.getAutogenerate();
					placeAsStack = placeBlockDialog.isPlaceAsStack();
					placeAsGroup = placeBlockDialog.isPlaceAsGroup();
				}
				else {
					IPinInfoProvider dlg = getAddPinListDialog(frame, pinlist, symDef);
					if (!dlg.selectPinList()) {
						return IActionEnum.eCanceled;
					}

					//For ring terminal, cancel the action if the pin is not selected
					if (IConnector.Statics.isRingTerminalTypeConnector(pinlist) && dlg.getPins().isEmpty()) {
						return IActionEnum.eCanceled;
					}

					pinSelection = dlg.getPins();

					autogenerate = dlg.getAutogenerate();
					reference = dlg.getReference();
					placeAsStack = dlg.getPlaceAsStack();
					placeAsGroup = dlg.getPlaceAsGroup();
					symDef = dlg.getSymbol();  // might be a different symbol
					block = dlg.getBlock();
				}
				pinProxies.addAll(pinSelection);
			}
		}
		else {
			pins = CollectionUtils.createList(pinlist.getPins());
			if (!pins.isEmpty()) {
				//check for pinduplication.
				IDesignContainer designContainer = DesignHelper.getDesign(pinlist);
				if (designContainer != null) {
					for (IAbstractPin sPin : pins) {
						if (!PinUtils.isPinPlaceableInDesign(sPin, designContainer)) {
							return IActionEnum.eCanceled;
						}
					}
				}
			}
		}

		// forward the rest of the behaviour to the sub actions for adding an instance with/without a symbol
		if (symDef != null) {
			return activateAddWithSymbol(e, pinlist, symDef, block, symbolpinMap, reference, withConductor);
		}
		return activateAddWithoutSymbol(e, pinlist, pins, autogenerate, reference, placeAsStack, placeAsGroup,
				pinProxies, withConductor);
	}

