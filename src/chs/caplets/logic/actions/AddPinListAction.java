	/**
	 * @return If only a single connectivity pinlist is selected, return it otherwise return null
	 */
	@Nullable protected IPinList getOperand()
	{
		IPinList pl = null;
		SelectSet selections = getController().getSelectMgr().getPreSelections();
		for (SelectedUIDObjectIterator it = selections.getSelectedUIDObjects(); it.hasNext(); ) {
			IUIDObject obj = it.getNext();
			if (obj instanceof IPinList) {
				if (pl == null) {
					pl = (IPinList) obj;
				}
				else {
					pl = null; // multiple connectivity pinlists selected ==> not enabled
					break;
				}
			}
		}
		if (pl instanceof IBackshell) {
			pl = null;
		}

		if (pl != null && LogicObjectLockFinder.isLogicObjectLockedInOtherSession(pl)) {
			pl = null;
		}
		return pl;
	}

	// TODO jacobt FEAT13040 : Move this lower in the action hierarachy?  It is overridden by the test action
	@Nullable protected ISymbolDef loadSymbolDef(IPinList pinlist)
	{
		ISymbolRef symRef = pinlist.getSymbolRef();
		if (symRef != null && !pinlist.isShared()) {
			// symbol def skeleton load time - use util to avoid temp objects here
			return CAFCommandHelper.loadSymbolDef(symRef.getSymbolUID(), false);
		}
		return null;
	}

